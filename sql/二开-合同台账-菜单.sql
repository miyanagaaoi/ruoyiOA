--   * 只新增菜单/按钮，**不动任何既有行**；可安全地在业务库 rad_oa 执行；
--   * 幂等写法：先按 menu_id 白名单 DELETE，再 INSERT（连续执行两次结果一致）。
--
-- ⚠ 人工步骤（脚本无法代劳）：本文件只建"权限点"，**不给任何角色授权**。
--   superAdmin 天然拥有全部权限；其它角色（采购主管/仓管员/财务/只读…）需要在
--   「系统管理 → 角色管理 → 修改 → 菜单权限」里勾选对应菜单与按钮，否则界面上看不到入口、
--   按钮点了也会 403。这一步请记入交付说明（见 sql/README-合同台账SQL.md）。
--
-- 菜单结构（1 目录 + 4 菜单 + 22 按钮 = 27 行；覆盖 26 个权限点）：
--   合同管理（目录 ctms）
--     ├─ 合同台账        ctms/contract/index    ctms:contract:list
--     │    └─ 查询/新增/编辑/删除/状态变更/导出 + 行项 查看/新增/编辑/删除 + 附件管理
--     ├─ 标签管理        ctms/tag/index         ctms:tag:list
--     │    └─ 新增/编辑/删除
--     ├─ 往来单位        ctms/partner/index     ctms:partner:list
--     │    └─ 查询/新增/编辑/删除/状态变更
--     └─ 迁移认领        ctms/migration/index   ctms:migration:list
--          └─ 扫描/认领/忽略
--
-- ⚠ `ctms:attachment:list` 是第 6 组（附件接入）新增的权限点（第 5 组没有新增）：
--   附件不是"合同的一条普通字段"，它有独立的存储与生命周期，所以给它一个自己的
--   读权限点；写动作（上传/删除）同时要求 `ctms:contract:edit` + `ctms:attachment:list`，
--   即"能改这份合同"且"看得见它的附件"。这样也避免出现"能上传却看不了"的角色。
-- ============================================================================

